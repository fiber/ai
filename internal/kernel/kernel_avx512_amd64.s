// Row-major-A variant of the 14×32 kernel (T-046): the A broadcasts come
// from a row-major tile with row stride lda floats instead of a k-major
// panel; rows 0–6 are addressed from AX with offsets lda·{0,1,2,3,4,5,6}
// (R11 = lda, R12 = 3·lda, R13 = 5·lda bytes), rows 7–13 from DI = AX +
// 7·lda. Same FMA count and register budget as gemmAVX512x14. Attention
// uses it to multiply unpacked query rows and probabilities.
//
// func gemmRMAVX512x14(k int, a *float32, lda int, b, c *float32, ldc int)
