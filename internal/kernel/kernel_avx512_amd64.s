	VFMADD231PS Z28, Z30, Z20 \
	VFMADD231PS Z29, Z30, Z21 \
	VFMADD231PS Z28, Z31, Z22 \
	VFMADD231PS Z29, Z31, Z23 \
	VBROADCASTSS AOFF+48(AX), Z30 \
	VBROADCASTSS AOFF+52(AX), Z31 \
	VFMADD231PS Z28, Z30, Z24 \
	VFMADD231PS Z29, Z30, Z25 \
	VFMADD231PS Z28, Z31, Z26 \
	VFMADD231PS Z29, Z31, Z27

// func gemmAVX512(k int, a, b, c *float32, ldc int)
TEXT ·gemmAVX512(SB), NOSPLIT, $0-40
	MOVQ k+0(FP), CX
	MOVQ a+8(FP), AX
	MOVQ b+16(FP), BX
	MOVQ c+24(FP), DX
	MOVQ ldc+32(FP), R8
	SHLQ $2, R8
	TESTQ CX, CX
	JZ   done
	// Pull the C tile into cache while the k loop runs: twelve rows ldc
	// apart, two lines each, otherwise fetched serially in the store phase.
	MOVQ DX, R9
	PREFETCHT0 (R9)
	PREFETCHT0 64(R9)
	ADDQ R8, R9
	PREFETCHT0 (R9)
	PREFETCHT0 64(R9)
	ADDQ R8, R9
	PREFETCHT0 (R9)
	PREFETCHT0 64(R9)
	ADDQ R8, R9
	PREFETCHT0 (R9)
	PREFETCHT0 64(R9)
	ADDQ R8, R9
	PREFETCHT0 (R9)
	PREFETCHT0 64(R9)
	ADDQ R8, R9
	PREFETCHT0 (R9)
	PREFETCHT0 64(R9)
	ADDQ R8, R9
	PREFETCHT0 (R9)
	PREFETCHT0 64(R9)
	ADDQ R8, R9
	PREFETCHT0 (R9)
	PREFETCHT0 64(R9)
	ADDQ R8, R9
	PREFETCHT0 (R9)
	PREFETCHT0 64(R9)
	ADDQ R8, R9
	PREFETCHT0 (R9)
	PREFETCHT0 64(R9)
	ADDQ R8, R9
	PREFETCHT0 (R9)
	PREFETCHT0 64(R9)
	ADDQ R8, R9
	PREFETCHT0 (R9)
	PREFETCHT0 64(R9)
	VPXORQ Z0, Z0, Z0
	VPXORQ Z1, Z1, Z1
	VPXORQ Z2, Z2, Z2
	VPXORQ Z3, Z3, Z3
	VPXORQ Z4, Z4, Z4
	VPXORQ Z5, Z5, Z5
	VPXORQ Z6, Z6, Z6
	VPXORQ Z7, Z7, Z7
	VPXORQ Z8, Z8, Z8
	VPXORQ Z9, Z9, Z9
	VPXORQ Z10, Z10, Z10
	VPXORQ Z11, Z11, Z11
	VPXORQ Z12, Z12, Z12
	VPXORQ Z13, Z13, Z13
	VPXORQ Z14, Z14, Z14
	VPXORQ Z15, Z15, Z15
	VPXORQ Z16, Z16, Z16
	VPXORQ Z17, Z17, Z17
	VPXORQ Z18, Z18, Z18
	VPXORQ Z19, Z19, Z19
	VPXORQ Z20, Z20, Z20
	VPXORQ Z21, Z21, Z21
	VPXORQ Z22, Z22, Z22
	VPXORQ Z23, Z23, Z23
	MOVQ CX, R9
	SHRQ $2, R9
	JZ   ktail
kloop4:
	KSTEP(0, 0)
	KSTEP(48, 128)
	KSTEP(96, 256)
	KSTEP(144, 384)
	ADDQ $192, AX
	ADDQ $512, BX
	DECQ R9
	JNZ  kloop4
ktail:
	ANDQ $3, CX
	JZ   store
kloop1:
	KSTEP(0, 0)
	ADDQ $48, AX
	ADDQ $128, BX
	DECQ CX
	JNZ  kloop1
store:
	CROW(Z0, Z1)
	CROW(Z2, Z3)
	CROW(Z4, Z5)
	CROW(Z6, Z7)
	CROW(Z8, Z9)
	CROW(Z10, Z11)
	CROW(Z12, Z13)
	CROW(Z14, Z15)
	CROW(Z16, Z17)
	CROW(Z18, Z19)
	CROW(Z20, Z21)
	CROW(Z22, Z23)
done:
	VZEROUPPER
	RET

