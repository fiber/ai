#include "textflag.h"

// AVX-512F GEMM micro-kernel, MR=12, NR=32:  C[12×32] += A[12×k] · B[k×32]
//
// Accumulators Z0..Z23 (row r uses Z(2r), Z(2r+1)), B in Z24/Z25,
// broadcast A in Z26/Z27. A is packed k-major (12 floats = 48 bytes per k),
// B is packed k-major (32 floats = 128 bytes per k).

#define KSTEP(AOFF, BOFF) \
	VMOVUPS BOFF(BX), Z24 \
	VMOVUPS BOFF+64(BX), Z25 \
	VBROADCASTSS AOFF(AX), Z26 \
	VBROADCASTSS AOFF+4(AX), Z27 \
	VFMADD231PS Z24, Z26, Z0 \
	VFMADD231PS Z25, Z26, Z1 \
	VFMADD231PS Z24, Z27, Z2 \
	VFMADD231PS Z25, Z27, Z3 \
	VBROADCASTSS AOFF+8(AX), Z26 \
	VBROADCASTSS AOFF+12(AX), Z27 \
	VFMADD231PS Z24, Z26, Z4 \
	VFMADD231PS Z25, Z26, Z5 \
	VFMADD231PS Z24, Z27, Z6 \
	VFMADD231PS Z25, Z27, Z7 \
	VBROADCASTSS AOFF+16(AX), Z26 \
	VBROADCASTSS AOFF+20(AX), Z27 \
	VFMADD231PS Z24, Z26, Z8 \
	VFMADD231PS Z25, Z26, Z9 \
	VFMADD231PS Z24, Z27, Z10 \
	VFMADD231PS Z25, Z27, Z11 \
	VBROADCASTSS AOFF+24(AX), Z26 \
	VBROADCASTSS AOFF+28(AX), Z27 \
	VFMADD231PS Z24, Z26, Z12 \
	VFMADD231PS Z25, Z26, Z13 \
	VFMADD231PS Z24, Z27, Z14 \
	VFMADD231PS Z25, Z27, Z15 \
	VBROADCASTSS AOFF+32(AX), Z26 \
	VBROADCASTSS AOFF+36(AX), Z27 \
	VFMADD231PS Z24, Z26, Z16 \
	VFMADD231PS Z25, Z26, Z17 \
	VFMADD231PS Z24, Z27, Z18 \
	VFMADD231PS Z25, Z27, Z19 \
	VBROADCASTSS AOFF+40(AX), Z26 \
	VBROADCASTSS AOFF+44(AX), Z27 \
	VFMADD231PS Z24, Z26, Z20 \
	VFMADD231PS Z25, Z26, Z21 \
	VFMADD231PS Z24, Z27, Z22 \
	VFMADD231PS Z25, Z27, Z23

#define CROW(R0, R1) \
	VADDPS (DX), R0, R0 \
	VADDPS 64(DX), R1, R1 \
	VMOVUPS R0, (DX) \
	VMOVUPS R1, 64(DX) \
	ADDQ R8, DX

// func gemmAVX512(k int, a, b, c *float32, ldc int)
TEXT ·gemmAVX512(SB), NOSPLIT, $0-40
	MOVQ k+0(FP), CX
	MOVQ a+8(FP), AX
	MOVQ b+16(FP), BX
	MOVQ c+24(FP), DX
	MOVQ ldc+32(FP), R8
	SHLQ $2, R8
	TESTQ CX, CX
	JZ   done
	VPXORQ Z0, Z0, Z0
	VPXORQ Z1, Z1, Z1
	VPXORQ Z2, Z2, Z2
	VPXORQ Z3, Z3, Z3
	VPXORQ Z4, Z4, Z4
	VPXORQ Z5, Z5, Z5
	VPXORQ Z6, Z6, Z6
	VPXORQ Z7, Z7, Z7
	VPXORQ Z8, Z8, Z8
	VPXORQ Z9, Z9, Z9
	VPXORQ Z10, Z10, Z10
	VPXORQ Z11, Z11, Z11
	VPXORQ Z12, Z12, Z12
	VPXORQ Z13, Z13, Z13
	VPXORQ Z14, Z14, Z14
	VPXORQ Z15, Z15, Z15
	VPXORQ Z16, Z16, Z16
	VPXORQ Z17, Z17, Z17
	VPXORQ Z18, Z18, Z18
	VPXORQ Z19, Z19, Z19
	VPXORQ Z20, Z20, Z20
	VPXORQ Z21, Z21, Z21
	VPXORQ Z22, Z22, Z22
	VPXORQ Z23, Z23, Z23
	MOVQ CX, R9
	SHRQ $2, R9
	JZ   ktail
kloop4:
	KSTEP(0, 0)
	KSTEP(48, 128)
	KSTEP(96, 256)
	KSTEP(144, 384)
	ADDQ $192, AX
	ADDQ $512, BX
	DECQ R9
	JNZ  kloop4
ktail:
	ANDQ $3, CX
	JZ   store
kloop1:
	KSTEP(0, 0)
	ADDQ $48, AX
	ADDQ $128, BX
	DECQ CX
	JNZ  kloop1
store:
	CROW(Z0, Z1)
	CROW(Z2, Z3)
	CROW(Z4, Z5)
	CROW(Z6, Z7)
	CROW(Z8, Z9)
	CROW(Z10, Z11)
	CROW(Z12, Z13)
	CROW(Z14, Z15)
	CROW(Z16, Z17)
	CROW(Z18, Z19)
	CROW(Z20, Z21)
	CROW(Z22, Z23)
done:
	VZEROUPPER
	RET
