// AVX-512F GEMM micro-kernel, MR=12, NR=32:  C[12×32] += A[12×k] · B[k×32]
// (the earlier default, kept as FIBERAI_KERNEL=avx512x12; see gemmAVX512x14)
//
// Accumulators Z0..Z23 (row r uses Z(2r), Z(2r+1)), B in Z24/Z25,
// broadcast A in Z26/Z27. A is packed k-major (12 floats = 48 bytes per k),
// B is packed k-major (32 floats = 128 bytes per k).

// KSTEP consumes one k of the packed panels. The prefetches keep A and B
// a few hundred bytes ahead in L1: with sixteen cores streaming panels
// out of L2/L3 at once the hardware prefetchers fall behind, which cost
// ~25 % of the kernel's single-core rate on Skylake-SP.
#define KSTEP(AOFF, BOFF) \
	PREFETCHT0 (BOFF+1024)(BX) \
	PREFETCHT0 (AOFF+384)(AX) \
	VMOVUPS BOFF(BX), Z24 \
	VMOVUPS BOFF+64(BX), Z25 \
	VBROADCASTSS AOFF(AX), Z26 \
	VBROADCASTSS AOFF+4(AX), Z27 \
	VFMADD231PS Z24, Z26, Z0 \
	VFMADD231PS Z25, Z26, Z1 \
	VFMADD231PS Z24, Z27, Z2 \
	VFMADD231PS Z25, Z27, Z3 \
	VBROADCASTSS AOFF+8(AX), Z26 \
	VBROADCASTSS AOFF+12(AX), Z27 \
	VFMADD231PS Z24, Z26, Z4 \
	VFMADD231PS Z25, Z26, Z5 \
	VFMADD231PS Z24, Z27, Z6 \
	VFMADD231PS Z25, Z27, Z7 \
	VBROADCASTSS AOFF+16(AX), Z26 \
	VBROADCASTSS AOFF+20(AX), Z27 \
	VFMADD231PS Z24, Z26, Z8 \
	VFMADD231PS Z25, Z26, Z9 \
	VFMADD231PS Z24, Z27, Z10 \
	VFMADD231PS Z25, Z27, Z11 \
	VBROADCASTSS AOFF+24(AX), Z26 \
	VBROADCASTSS AOFF+28(AX), Z27 \
	VFMADD231PS Z24, Z26, Z12 \
	VFMADD231PS Z25, Z26, Z13 \
	VFMADD231PS Z24, Z27, Z14 \
	VFMADD231PS Z25, Z27, Z15 \
	VBROADCASTSS AOFF+32(AX), Z26 \
	VBROADCASTSS AOFF+36(AX), Z27 \
	VFMADD231PS Z24, Z26, Z16 \
	VFMADD231PS Z25, Z26, Z17 \
	VFMADD231PS Z24, Z27, Z18 \
	VFMADD231PS Z25, Z27, Z19 \
	VBROADCASTSS AOFF+40(AX), Z26 \
	VBROADCASTSS AOFF+44(AX), Z27 \
	VFMADD231PS Z24, Z26, Z20 \
	VFMADD231PS Z25, Z26, Z21 \
	VFMADD231PS Z24, Z27, Z22 \
	VFMADD231PS Z25, Z27, Z23

#define CROW(R0, R1) \
	VADDPS (DX), R0, R0 \
	VADDPS 64(DX), R1, R1 \
	VMOVUPS R0, (DX) \
	VMOVUPS R1, 64(DX) \
	ADDQ R8, DX

#define KSTEP14(AOFF, BOFF) \
	PREFETCHT0 (BOFF+1024)(BX) \
	PREFETCHT0 (AOFF+448)(AX) \
	VMOVUPS BOFF(BX), Z28 \
	VMOVUPS BOFF+64(BX), Z29 \
	VBROADCASTSS AOFF+0(AX), Z30 \
	VBROADCASTSS AOFF+4(AX), Z31 \
	VFMADD231PS Z28, Z30, Z0 \
	VFMADD231PS Z29, Z30, Z1 \
	VFMADD231PS Z28, Z31, Z2 \
	VFMADD231PS Z29, Z31, Z3 \
	VBROADCASTSS AOFF+8(AX), Z30 \
	VBROADCASTSS AOFF+12(AX), Z31 \
	VFMADD231PS Z28, Z30, Z4 \
	VFMADD231PS Z29, Z30, Z5 \
	VFMADD231PS Z28, Z31, Z6 \
	VFMADD231PS Z29, Z31, Z7 \
	VBROADCASTSS AOFF+16(AX), Z30 \
	VBROADCASTSS AOFF+20(AX), Z31 \
	VFMADD231PS Z28, Z30, Z8 \
	VFMADD231PS Z29, Z30, Z9 \
	VFMADD231PS Z28, Z31, Z10 \
	VFMADD231PS Z29, Z31, Z11 \
	VBROADCASTSS AOFF+24(AX), Z30 \
	VBROADCASTSS AOFF+28(AX), Z31 \
	VFMADD231PS Z28, Z30, Z12 \
	VFMADD231PS Z29, Z30, Z13 \
	VFMADD231PS Z28, Z31, Z14 \
	VFMADD231PS Z29, Z31, Z15 \
	VBROADCASTSS AOFF+32(AX), Z30 \
	VBROADCASTSS AOFF+36(AX), Z31 \
	VFMADD231PS Z28, Z30, Z16 \
	VFMADD231PS Z29, Z30, Z17 \
	VFMADD231PS Z28, Z31, Z18 \
	VFMADD231PS Z29, Z31, Z19 \
	VBROADCASTSS AOFF+40(AX), Z30 \
